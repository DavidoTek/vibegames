// Box-drawing: which arms a glyph has (U, R, D, L) and their weight (1 = single, 2 = double).
const BOX = {
  "─": "0101", "│": "1010", "┌": "0110", "┐": "0011", "└": "1100", "┘": "1001",
  "├": "1110", "┤": "1011", "┬": "0111", "┴": "1101", "┼": "1111",
  "═": "0202", "║": "2020", "╔": "0220", "╗": "0022", "╚": "2200", "╝": "2002",
  "╠": "2220", "╣": "2022", "╦": "0222", "╩": "2202", "╬": "2222",
};

const glyphs = new Map();

function blank() { return new Uint8Array(16); }

function parse() {
  const lines = DATA.split("\n");
  let ch = null, rows = [];
  const flush = () => {
    if (ch === null) return;
    const g = blank();
    rows.forEach((r, i) => {
      let bits = 0;
      for (let x = 0; x < 7; x++) if (r[x] === "#") bits |= 0x80 >> x;
      g[2 + i] = bits;
    });
    glyphs.set(ch, g);
  };
  for (const line of lines) {
    if (line.length === 7) rows.push(line);
    else if (line.length === 1) { flush(); ch = line; rows = []; }
  }
  flush();
  glyphs.set(" ", blank());
}

function setPx(g, x, y) { if (x >= 0 && x < 8 && y >= 0 && y < 16) g[y] |= 0x80 >> x; }
function hline(g, y, x0, x1) { for (let x = Math.min(x0, x1); x <= Math.max(x0, x1); x++) setPx(g, x, y); }
function vline(g, x, y0, y1) { for (let y = Math.min(y0, y1); y <= Math.max(y0, y1); y++) setPx(g, x, y); }

// Single lines run through column 3 and row 8; double lines use columns 2/4 and rows 7/9.
function boxGlyph(spec) {
  const g = blank();
  const [u, r, d, l] = [...spec].map(Number);
  const double = Math.max(u, r, d, l) === 2;
  if (!double) {
    if (u) vline(g, 3, 0, 8);
    if (d) vline(g, 3, 8, 15);
    if (l) hline(g, 8, 0, 3);
    if (r) hline(g, 8, 3, 7);
    return g;
  }
  const n = [u, r, d, l].filter(Boolean).length;
  // corner (h = -1 left / +1 right, v = -1 up / +1 down): outer and inner tracks
  const corner = (h, v, inner, outer) => {
    const edgeX = h > 0 ? 7 : 0, edgeY = v > 0 ? 15 : 0;
    if (outer) { hline(g, 8 - v, 3 - h, edgeX); vline(g, 3 - h, 8 - v, edgeY); }
    if (inner) { hline(g, 8 + v, 3 + h, edgeX); vline(g, 3 + h, 8 + v, edgeY); }
  };
  if (n === 2 && u && d) { vline(g, 2, 0, 15); vline(g, 4, 0, 15); return g; }
  if (n === 2 && l && r) { hline(g, 7, 0, 7); hline(g, 9, 0, 7); return g; }
  if (n === 2) { corner(r ? 1 : -1, d ? 1 : -1, true, true); return g; }
  if (u && r) corner(1, -1, true, false);
  if (r && d) corner(1, 1, true, false);
  if (d && l) corner(-1, 1, true, false);
  if (l && u) corner(-1, -1, true, false);
  if (n === 3) {
    if (!l) vline(g, 2, 0, 15);
    if (!r) vline(g, 4, 0, 15);
    if (!u) hline(g, 7, 0, 7);
    if (!d) hline(g, 9, 0, 7);
  }
  return g;
}

function patternGlyph(fn) {
  const g = blank();
  for (let y = 0; y < 16; y++) for (let x = 0; x < 8; x++) if (fn(x, y)) setPx(g, x, y);
  return g;
}

function build() {
  parse();
  for (const [ch, spec] of Object.entries(BOX)) glyphs.set(ch, boxGlyph(spec));
  glyphs.set("█", patternGlyph(() => true));
  glyphs.set("▀", patternGlyph((x, y) => y < 8));
  glyphs.set("▄", patternGlyph((x, y) => y >= 8));
  glyphs.set("▌", patternGlyph((x) => x < 4));
  glyphs.set("▐", patternGlyph((x) => x >= 4));
  glyphs.set("░", patternGlyph((x, y) => (y % 2 === 0 && x % 4 === 0) || (y % 2 === 1 && x % 4 === 2)));
  glyphs.set("▒", patternGlyph((x, y) => (x + y) % 2 === 0));
  glyphs.set("▓", patternGlyph((x, y) => !(x % 2 === 1 && y % 2 === 1)));
  glyphs.set("■", patternGlyph((x, y) => x >= 1 && x <= 6 && y >= 5 && y <= 11));
  glyphs.set("▬", patternGlyph((x, y) => y >= 9 && y <= 12));
}

build();

const fallback = glyphs.get("?");

export function glyph(ch) {
  return glyphs.get(ch) || fallback;
}

export function hasGlyph(ch) {
  return glyphs.has(ch);
}
